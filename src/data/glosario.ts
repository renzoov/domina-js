/** id de un término: su nombre sin tildes, en minúsculas y con guiones */
export const idTermino = (termino: string) =>
  termino
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
